export function computeStats(inventory = [], equipped = { cord: null, beads: [] }) {
  const byId = new Map(inventory.map((item) => [item.id, ITEMS[item.defId]]));
  const selectedCord = byId.get(equipped.cord);
  const capacity = selectedCord?.type === 'cord' ? selectedCord.capacity : 0;
  const result = { moveSpeed: 0, bowSpeed: 0, dropRate: 0, capacity };
  const selected = [
    selectedCord,
    ...[...new Set(equipped.beads || [])]
      .slice(0, capacity)
      .map((id) => byId.get(id))
      .filter((item) => item?.type === 'bead'),
  ];
  for (const item of selected)
    for (const stat of ['moveSpeed', 'bowSpeed', 'dropRate'])
      result[stat] += item?.stats?.[stat] || 0;
  // Bound server effects even with a complete 108-bead collection.
  result.moveSpeed = Math.min(result.moveSpeed, 75);
  result.bowSpeed = Math.min(result.bowSpeed, 200);
  result.dropRate = Math.min(result.dropRate, 100);
  return result;
}
